"""Shared helpers for code exporters."""

from __future__ import annotations

import re
from dataclasses import dataclass

from ..engine.spec import BacktestConfig, Strategy
from ..rules.expr import Call, Expr, Lag, Logic, max_lookback, walk


@dataclass
class ExportContext:
    strategy: Strategy
    config: BacktestConfig
    tick_size: float
    point_value: float
    symbol: str

    @property
    def name(self) -> str:
        base = self.strategy.name or "AlphaForgeStrategy"
        return re.sub(r"[^A-Za-z0-9_]", "_", base)

    def warmup(self) -> int:
        exprs: list[Expr] = [self.strategy.entry_expr()]
        if self.strategy.exits.exit_signal is not None:
            exprs.append(self.strategy.exits.exit_signal.expr())
        lb = max(max_lookback(e) for e in exprs)
        needs_atr = any(v is not None for v in (self.strategy.exits.stop_atr, self.strategy.exits.target_atr, self.strategy.exits.trail_atr))
        if needs_atr:
            lb = max(lb, 4 * self.strategy.exits.atr_len + 1)
        return lb + 1

    def calls(self) -> list[Call]:
        """Unique indicator calls in dependency order (inner first)."""
        exprs: list[Expr] = [self.strategy.entry_expr()]
        if self.strategy.exits.exit_signal is not None:
            exprs.append(self.strategy.exits.exit_signal.expr())
        seen: dict[Call, None] = {}
        for e in exprs:
            for node in reversed(list(walk(e))):
                if isinstance(node, Call) and node not in seen:
                    seen[node] = None
        return list(seen)


def header_lines(ctx: ExportContext, comment: str) -> list[str]:
    s = ctx.strategy
    c = ctx.config.costs
    lines = [
        "Generated by AlphaForge (independent open-source strategy generator).",
        f"Rules: {s.describe()}",
        f"Execution model: decisions at bar close, market orders at next bar open; stops/targets from ATR({s.exits.atr_len}) on the signal bar.",
        f"Backtest assumptions: commission {c.commission:g} per unit per side, slippage {c.slippage_ticks:g} ticks per side, tick size {ctx.tick_size:g}, point value {ctx.point_value:g}.",
        "Hypothetical results do not guarantee future performance. Verify on the target platform before trading.",
    ]
    return [f"{comment} {x}" for x in lines]


def is_and(e: Expr) -> bool:
    return isinstance(e, Logic) and e.op == "and"


def flatten_lags(e: Expr) -> bool:
    return isinstance(e, Lag)
